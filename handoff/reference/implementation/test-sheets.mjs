import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {parseTable,combineExactEvents,gvizDate,parseGviz} from './google-sheets-adapter.mjs';
const fixture=k=>JSON.parse(readFileSync(new URL(`../source-snapshots/${k}-sheet.json`,import.meta.url)));
const events=parseTable(fixture('events').table);
assert.equal(events.records.length,44);
assert.equal(events.records[0].name,'World Economic Forum Annual Meeting');
assert.equal(events.records[0].size,'Large');
assert.equal(events.records[0].scope,'International');
assert.ok(events.records[0].description.includes('global agenda'));
assert.equal(events.availableFields.includes('ticketPrice'),false);
assert.equal(combineExactEvents(events.records).length,43);
assert.equal(combineExactEvents(events.records).filter(r=>r.sourceVariants).length,1);
assert.equal(gvizDate('Date(2026,0,19)'),'2026-01-19');
assert.equal(parseTable(fixture('vcs').table).records.length,66);
assert.equal(parseTable(fixture('robotics').table).records.length,157);
const legacy={cols:[{label:''},{label:''}],rows:[{c:[{v:'Event Name'},{v:'Ticket Price'}]},{c:[{v:'Test event'},{v:'Free'}]}]};
assert.equal(parseTable(legacy).records[0].ticketPrice,'Free');
assert.equal(parseGviz('google.visualization.Query.setResponse('+JSON.stringify({status:'ok',table:legacy})+');').records.length,1);
assert.throws(()=>parseTable({cols:[{label:'Unknown'}],rows:[{c:[{v:'Unknown'}]}]}));
assert.throws(()=>parseGviz('not a response'));
assert.equal(combineExactEvents([{name:'Same',startDate:'2026-01-01',finishDate:'2026-01-01',officialUrl:'https://example.com'},{name:'Same',startDate:'2026-02-01',finishDate:'2026-02-01',officialUrl:'https://example.com'}]).length,2);
console.log('PASS: headers, first event, field mapping, missing price, duplicate identity, distinct dates, legacy headers, 66 VCs and 157 robotics organisations.');
